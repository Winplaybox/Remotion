export interface PostMeta { title: string; description: string; tags: string[]; caption: string; language: string; categoryId: string }

export interface ChannelConfig {
  name: string;
  composition: string;
  /** Date (Asia/Kolkata) on which post #1 goes live. */
  startDate: string;
  /** Publish times in IST, "HH:MM". Post number = (day - 1) * slots.length + slotIndex + 1. */
  slots: readonly string[];
  narrated: boolean;
  /**
   * false = only published when the repo variable LIVE_<ID>=true is set (ID = channel id upper-cased, "-" -> "_").
   * Used to switch a channel over from another pipeline on a chosen day without double-posting.
   */
  autoPublish: boolean;
  /** GitHub secret holding this channel's YouTube OAuth token JSON. */
  youtubeTokenSecret: string;
  /** GitHub secret prefix for Meta: <PREFIX>_PAGE_ID, <PREFIX>_IG_USER_ID, <PREFIX>_PAGE_TOKEN. */
  metaSecretPrefix: string;
  resolve: (n: number) => unknown;
  meta: (n: number) => PostMeta;
  /** Short Hinglish voice clips placed at fixed times (puzzle channels). Generated by Edge TTS in Actions. */
  voice?: (n: number) => VoiceLine[];
  /** Answer comment posted on the video once it is public (pin it in YouTube Studio). */
  answer?: (n: number) => string;
}

