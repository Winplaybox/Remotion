export interface PostMeta {
  title: string; description: string; tags: string[]; caption: string; language: string; categoryId: string;
  /** Long videos: part cut as the vertical Instagram/Facebook teaser (seconds) + its closing banner. */
  teaser?: { start: number; length: number; banner: string };
}

export interface ChannelConfig {
  name: string;
  composition: string;
  /** Date (Asia/Kolkata) on which post #1 goes live. */
  startDate: string;
  /** Publish times in IST, "HH:MM". Post number = (day - 1) * slots.length + slotIndex + 1. */
  slots: readonly string[];
  /** Only post on these weekdays (IST, 0 = Sunday). Post numbers then count only those days. Default: every day. */
  weekdays?: readonly number[];
  /** Long video (16:9): Instagram / Facebook get a vertical teaser that sends viewers to YouTube; no Pinterest pin. */
  longForm?: boolean;
  /** Use this channel's connected Instagram / Facebook / Pinterest accounts (same brand, different format). */
  socialAccount?: string;
  narrated: boolean;
  /**
   * false = only published when the repo variable LIVE_<ID>=true is set (ID = channel id upper-cased, "-" -> "_").
   * Used to switch a channel over from another pipeline on a chosen day without double-posting.
   */
  autoPublish: boolean;
  /** GitHub secret holding this channel's YouTube OAuth token JSON. */
  youtubeTokenSecret: string;
  /** GitHub secret prefix for Meta: <PREFIX>_PAGE_ID, <PREFIX>_IG_USER_ID, <PREFIX>_PAGE_TOKEN. */
  metaSecretPrefix: string;
  /** YouTube handle used in the "subscribe on YouTube" call to action on Instagram / Facebook / Pinterest. */
  youtubeHandle: string;
  /** GitHub secret prefix for Pinterest: <PREFIX>_REFRESH_TOKEN, <PREFIX>_BOARD_ID (app: PINTEREST_APP_ID / _SECRET). */
  pinterestSecretPrefix: string;
  resolve: (n: number) => unknown;
  meta: (n: number) => PostMeta;
  /** Timed narration clips generated by Edge TTS in Actions. */
  voice?: (n: number) => VoiceLine[];
  /** Optional per-channel Edge TTS voice override. */
  voiceName?: string;
  /** Answer comment posted on the video once it is public (pin it in YouTube Studio). */
  answer?: (n: number) => string;
  /** From this post on the answer is revealed in the next video; the comment is posted once post n+1 is public. */
  answerInNextFrom?: number;
  /** Structured answer: comment auto-reply checks viewers' guesses against it (YouTube / Instagram / Facebook). */
  quiz?: Quiz;
}

