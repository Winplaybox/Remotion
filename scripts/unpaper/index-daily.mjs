#!/usr/bin/env node
/**
 * Regenerates content/unpaper/daily/index.ts from the episode files in that folder.
 *
 *   npm run unpaper:index            # write the index
 *   npm run unpaper:index -- --check # exit 1 if the committed index is stale (no write)
 *   ... --dir <folder>               # another folder (tests)
 *
 * Only files named YYYY-MM-DD-am.json / YYYY-MM-DD-pm.json are listed. A file that is not valid JSON is left out
 * with a warning (its slot is then skipped by the publisher) so one broken file can never break the build for every
 * channel. Schema and source checks happen at publish time (engines/unpaper-short/src/daily.ts).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const dirArg = process.argv.indexOf("--dir");
const dir = dirArg > 0 ? path.resolve(process.argv[dirArg + 1]) : path.join(root, "content", "unpaper", "daily");
const out = path.join(dir, "index.ts");
const RE = /^(\d{4}-\d{2}-\d{2})-(am|pm)\.json$/;

export function buildIndex(files, read) {
  const ok = [];
  const warnings = [];
  for (const f of [...files].sort()) {
    if (!RE.test(f)) { if (f.endsWith(".json")) warnings.push(`${f}: name must be YYYY-MM-DD-am.json or -pm.json — ignored`); continue; }
    try { JSON.parse(read(f)); ok.push(f); } catch (e) { warnings.push(`${f}: not valid JSON (${e.message}) — left out, that slot will be skipped`); }
  }
  const lines = [
    "// GENERATED by `npm run unpaper:index` (scripts/unpaper/index-daily.mjs). Do not edit by hand.",
    "// Lists every daily Unpaper episode in this folder: YYYY-MM-DD-am.json (09:00 IST) / -pm.json (19:00 IST).",
    ...ok.map((f, i) => `import e${i} from "./${f}";`),
    "",
    "export const UNPAPER_DAILY: Record<string, unknown> = {",
    ...ok.map((f, i) => `  "${f.replace(/\.json$/, "")}": e${i},`),
    "};",
    ""
  ];
  return { text: lines.join("\n"), warnings, count: ok.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(dir, { recursive: true });
  const { text, warnings, count } = buildIndex(fs.readdirSync(dir), (f) => fs.readFileSync(path.join(dir, f), "utf8"));
  for (const w of warnings) console.warn(`::warning::unpaper daily ${w}`);
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (cur !== text) { console.error("content/unpaper/daily/index.ts is stale — run npm run unpaper:index"); process.exit(1); }
    console.log(`[unpaper:index] up to date (${count} episode(s))`);
  } else {
    fs.writeFileSync(out, text);
    console.log(`[unpaper:index] ${count} episode(s) -> ${path.relative(root, out) || out}`);
  }
}
